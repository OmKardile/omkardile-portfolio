#!/usr/bin/env python3
"""verify-one-source.py — [1.5.9] one source, many outputs, enforced.

Run against any base URL (default http://127.0.0.1:3000):

    python3 scripts/verify-one-source.py [BASE_URL]

  Static
    S1  public/resume.pdf: exactly 1 page, contact line matches site.ts
        (the drift that shipped is now impossible)
    S2  /resume route imports site.ts (no retyped contact), receipt-qr.ts
        is generated (not hand-edited), llms route compiles from data

  Rendered
    R1  /resume: contact carries site.email + site.phone + is-a.dev URL;
        roles == site.experience Role count; skills line non-empty
    R2  /llms.txt: 200, text/plain, builds compiled (11), the dated
        ledger present, provenance line in
    R3  /receipt: 3 proofs with verified manifests, totals include
        'unverifiable claims 0', owed list == ledgerOwed count with dates,
        the vCard QR svg renders, 'nothing left your browser' claim shown
    R4  /now: resume promise settled stamped [1.5.9], the SSShopee credit
        owed entry dated, open count == 5
    R5  home: PatelNetworks card leads with the manifest-verified stack
"""

import pathlib
import re
import sys

from playwright.sync_api import sync_playwright
from pypdf import PdfReader

ROOT = pathlib.Path(__file__).resolve().parents[1]
BASE = sys.argv[1] if len(sys.argv) > 1 else "http://127.0.0.1:3000"
EVIDENCE = ROOT / "download" / "one-source-evidence"
EVIDENCE.mkdir(parents=True, exist_ok=True)

site_ts = (ROOT / "src" / "data" / "site.ts").read_text()
email = re.search(r"email: '([^']*)'", site_ts).group(1)
phone = re.search(r"phone: '([^']*)'", site_ts).group(1)
roles_count = len(re.findall(r"kind: 'Role'", site_ts))

results = []


def check(name, ok, detail=""):
    results.append((name, ok, detail))
    print(f"  {'PASS' if ok else 'FAIL'}  {name}" + (f"  — {detail}" if detail and not ok else ""))


reader = PdfReader(ROOT / "public" / "resume.pdf")
try:
    text = reader.pages[0].extract_text()
except Exception:
    import subprocess
    text = subprocess.run(["pdftotext", str(ROOT / "public" / "resume.pdf"), "-"],
                          capture_output=True, text=True, timeout=30).stdout
text = text.replace("\u00a0", " ")
check("S1 resume.pdf: 1 page, contact from the one source",
      len(reader.pages) == 1 and email in text and "omkardile.is-a.dev" in text and "88887 85222" in text.replace("\u00a0", " "),
      f"pages={len(reader.pages)} email={'ok' if email in text else 'DRIFTED'}")

resume_src = (ROOT / "src" / "app" / "resume" / "page.tsx").read_text()
qr_src = (ROOT / "src" / "data" / "receipt-qr.ts").read_text()
receipt_src = (ROOT / "src" / "app" / "receipt" / "page.tsx").read_text()
llms_src = (ROOT / "src" / "app" / "llms.txt" / "route.ts").read_text()
check("S2a resume route renders from site.ts",
      "from '@/data/site'" in resume_src and "resumeEducation" in resume_src
      and "buildScans" in resume_src and "site.email" in resume_src and "site.phone" in resume_src)
check("S2b receipt QR generated from site fields",
      "Generated by scripts/build-receipt-qr.py" in qr_src and "receiptQrSize" in qr_src)
check("S2c llms.txt compiles from the data files",
      "from '@/data/site'" in llms_src and "ledgerOwed" in llms_src and "buildScans" in llms_src)
check("S2d receipt page is fully static (no client fetch)",
      "fetch(" not in receipt_src and "useEffect" not in receipt_src)

print(f"\n== rendered: {BASE}/resume ==")
with sync_playwright() as p:
    browser = p.chromium.launch()
    page = browser.new_page(viewport={"width": 794, "height": 1123}, device_scale_factor=1)
    page.goto(BASE + "/resume", wait_until="networkidle")
    body = page.locator("body").inner_text()
    check("R1a resume contact from the one source",
          email in body and phone in body and "omkardile.is-a.dev" in body)
    check("R1b roles rendered from site.experience", body.count(" to ") >= roles_count,
          f"roles={roles_count}")
    check("R1c skills line compiled", "UX Design" in body and "TypeScript" in body)
    check("R1d proofs carry the verified scans",
          "verified from the repo manifest" in body)
    page.screenshot(path=str(EVIDENCE / "resume-route.png"), full_page=True)

    print(f"== rendered: {BASE}/llms.txt ==")
    page.goto(BASE + "/llms.txt", wait_until="networkidle")
    llms = page.locator("body").inner_text()
    check("R2a llms.txt served as plain text", "text/plain" in
          (page.locator("pre").first.get_attribute("style") or "") or len(llms) > 500)
    check("R2b builds compiled from data", "Builds (11" in llms and "verified from the repo manifest" in llms)
    check("R2c the dated ledger is in", "[owes, 2026-11-13]" in llms and "settled, each stamped" in llms)
    check("R2d provenance line in", "compiled from src/data/site.ts" in llms)
    page.screenshot(path=str(EVIDENCE / "llms-txt.png"), full_page=True)

    print(f"== rendered: {BASE}/receipt ==")
    page.goto(BASE + "/receipt", wait_until="networkidle")
    body = page.locator("body").inner_text()
    check("R3a three proofs with verified manifests",
          "PROOFS — 3 OF" in body and "VERIFIED FROM THE MANIFEST" in body)
    check("R3b totals honest", "UNVERIFIABLE CLAIMS" in body and "0" in body.split("UNVERIFIABLE CLAIMS")[1][:4])
    check("R3c owed list with dates", "OWED — OPEN PROMISES, DATED" in body and "2026-11-13" in body)
    qr_visible = page.locator('svg[aria-label*="vCard"]').is_visible()
    check("R3d vCard QR renders", qr_visible)
    check("R3e privacy claim printed", "NOTHING ABOUT THIS VISIT LEFT YOUR BROWSER" in body)
    page.locator("section").first.bounding_box()
    page.screenshot(path=str(EVIDENCE / "receipt.png"), full_page=True)

    print(f"== rendered: {BASE}/now ==")
    page.goto(BASE + "/now", wait_until="networkidle")
    body = page.locator("body").inner_text()
    check("R4a resume promise settled, stamped [1.5.9]",
          "Resume cut to one page" in body and "[1.5.9]" in body)
    check("R4b SSShopee credit owed, dated",
          "SSShopee GST receipt credit" in body and "2026-11-13" in body)
    check("R4c open count is five", "OWED · 5 OPEN" in body, [l for l in body.splitlines() if "OWED" in l][:1])

    print(f"== rendered: {BASE} ==")
    page.goto(BASE, wait_until="networkidle")
    body = page.locator("body").inner_text()
    check("R5 PatelNetworks leads with the verified stack",
          "Next.js 16 · React 19 · Prisma 6" in body)
    browser.close()

passed = sum(1 for _, ok, _ in results if ok)
print(f"\n{passed}/{len(results)} checks passed")
if passed < len(results):
    sys.exit(1)
print(f"Evidence: {EVIDENCE}")
