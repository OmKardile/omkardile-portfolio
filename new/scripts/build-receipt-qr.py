#!/usr/bin/env python3
"""build-receipt-qr.py — regenerate src/data/receipt-qr.ts from site.ts.

The candidate receipt's QR encodes a vCard whose fields are read straight
out of src/data/site.ts (name, role, email, phone, url) — the one source
again, so the QR and the resume and the site can't drift apart. Run:

    python3 scripts/build-receipt-qr.py
"""

import pathlib
import re

import qrcode

ROOT = pathlib.Path(__file__).resolve().parents[1]
site_ts = (ROOT / "src" / "data" / "site.ts").read_text()


def field(key):
    m = re.search(rf"{key}: '([^']*)'", site_ts)
    if not m:
        raise SystemExit(f"site.ts is missing {key}")
    return m.group(1)


name = field("name")
role = field("role")
email = field("email")
phone = field("phone")
url = field("url")

tel = re.sub(r"[^+\d]", "", phone)

vcard = "\n".join(
    [
        "BEGIN:VCARD",
        "VERSION:3.0",
        f"N:{name.split()[-1]};{name.split()[0]};;;",
        f"FN:{name}",
        f"TITLE:{role}",
        f"TEL;TYPE=CELL:{tel}",
        f"EMAIL:{email}",
        f"URL:{url}",
        f"ADR;TYPE=HOME:;;{'Pune'};;;{'India'}",
        "END:VCARD",
    ]
)

qr = qrcode.QRCode(error_correction=qrcode.constants.ERROR_CORRECT_M, border=1)
qr.add_data(vcard)
qr.make(fit=True)
matrix = qr.get_matrix()
size = len(matrix)

# One SVG path for the whole matrix — dark modules as 1×1 squares.
parts = []
for y, row in enumerate(matrix):
    for x, dark in enumerate(row):
        if dark:
            parts.append(f"M{x} {y}h1v1h-1z")
path = "".join(parts)

out = f'''/* Generated by scripts/build-receipt-qr.py — the vCard QR on /receipt,
   built from the contact fields in src/data/site.ts (one source: the QR
   re-encodes whatever the site says, so it can't drift from it). Regenerate
   with scripts/build-receipt-qr.py; don't hand-edit. */

export const receiptQrPath = {path!r};
export const receiptQrSize = {size};
'''

(ROOT / "src" / "data" / "receipt-qr.ts").write_text(out)
print(f"wrote src/data/receipt-qr.ts — {size}×{size} modules, vCard for {name} <{email}>")
